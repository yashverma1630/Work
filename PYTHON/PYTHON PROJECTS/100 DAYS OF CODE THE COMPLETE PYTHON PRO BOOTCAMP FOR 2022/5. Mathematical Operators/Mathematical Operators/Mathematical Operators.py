# PEMDAS

# ()
# **
# * or /
# + or -

print(1+1) #Addition
print(2-1) #Subtraction
print(3*4) #Multiplication
print(2**3) #Exponential
print(6/5) #Devision (float type result)
print(7//2) #Devision without decimal. integer type result

print(3*3+3/3-3) # this will result following PEMDAS rule

print(3*(3+3)/3-3) #this will result in 3. we can use paranthesis to perform with more specificity.